#!/usr/bin/env npx tsx
/**
 * Writes tests/endpoints.test.ts from the OpenAPI spec: every endpoint has its method on
 * the client, and calling it sends `GET <path>` with the API key. A spec change that the
 * client does not follow fails the suite.
 *
 *   npx tsx scripts/generate-endpoint-tests.ts --spec <file or URL>
 */
import { readFile, writeFile } from "node:fs/promises";

interface Operation {
  operationId?: string;
  tags?: string[];
  parameters?: Array<{ name: string; in: string; required?: boolean; schema?: { type?: string; enum?: string[] } }>;
}

let source = process.env.SPEC ?? "https://api.socialapi.sh/openapi.json";
for (let i = 2; i < process.argv.length; i += 1) {
  if (process.argv[i] === "--spec") source = process.argv[(i += 1)]!;
  else throw new Error(`Unknown argument: ${process.argv[i]}`);
}

const spec = (
  /^https?:\/\//.test(source)
    ? await (await fetch(source)).json()
    : JSON.parse(await readFile(source, "utf8"))
) as { paths?: Record<string, Record<string, Operation>> };

const property = (tag: string) => tag.toLowerCase().replace(/[^a-z0-9]/g, "");
const lowerFirst = (text: string) => text.charAt(0).toLowerCase() + text.slice(1);

/** A value for a required parameter, by its type. */
function sample(schema: Operation["parameters"] extends Array<infer P> | undefined ? P : never): string {
  if (schema.schema?.enum?.length) return JSON.stringify(schema.schema.enum[0]);
  if (schema.schema?.type === "integer" || schema.schema?.type === "number") return "1";
  return JSON.stringify("x");
}

const cases: string[] = [];
for (const [path, item] of Object.entries(spec.paths ?? {})) {
  const operation = item.get;
  const tag = operation?.tags?.[0];
  if (!operation?.operationId || !tag) continue;
  const prefix = property(tag);
  const id = operation.operationId;
  const name = id.toLowerCase().startsWith(prefix) && id.length > prefix.length ? lowerFirst(id.slice(prefix.length)) : id;
  const query = (operation.parameters ?? []).filter((p) => p.in === "query");
  const required = query.filter((p) => p.required);
  const args = query.length === 0 ? "" : `{ ${required.map((p) => `${p.name}: ${sample(p)}`).join(", ")} }`;
  cases.push(`  [${JSON.stringify(`client.${prefix}.${name}`)}, ${JSON.stringify(path)}, (c) => c.${prefix}.${name}(${args})],`);
}

await writeFile(
  "tests/endpoints.test.ts",
  `// Generated by scripts/generate-endpoint-tests.ts from the OpenAPI spec. Do not edit by hand.
import { describe, expect, it } from "vitest";
import { SocialAPI } from "../src/index.js";

const ENDPOINTS: Array<[string, string, (client: SocialAPI) => Promise<unknown>]> = [
${cases.join("\n")}
];

describe("every endpoint", () => {
  it.each(ENDPOINTS)("%s sends GET %s", async (_name, path, invoke) => {
    const seen: Request[] = [];
    const client = new SocialAPI({
      apiKey: "sapi_test",
      fetch: async (input, init) => {
        seen.push(new Request(input as string, init));
        return new Response(JSON.stringify({ data: [], pagination: { hasMore: false } }), {
          headers: { "content-type": "application/json" },
        });
      },
    });
    await invoke(client).catch(() => undefined);
    expect(seen).toHaveLength(1);
    const request = seen[0]!;
    expect(request.method).toBe("GET");
    expect(new URL(request.url).pathname).toBe(path);
    expect(request.headers.get("authorization")).toBe("Bearer sapi_test");
  });
});
`,
);
console.log(`Wrote tests/endpoints.test.ts (${cases.length} endpoints).`);
