#!/usr/bin/env npx tsx
/**
 * Writes src/client.ts, the `SocialAPI` client, from the OpenAPI spec: one property per
 * network (`client.tiktok`), one method per endpoint named after its path
 * (`client.tiktok.postCommentReplies(...)`), each calling the generated API class and
 * turning a refusal into a `SocialAPIError`.
 *
 *   npx tsx scripts/generate-client.ts --spec <file or URL>
 */
import { readFile, writeFile } from "node:fs/promises";

interface Operation {
  operationId?: string;
  summary?: string;
  description?: string;
  tags?: string[];
  parameters?: Array<{ name: string; in: string; required?: boolean }>;
}

interface Spec {
  paths?: Record<string, Record<string, Operation>>;
}

const DEFAULT_SPEC = "https://api.socialapi.sh/openapi.json";

async function loadSpec(source: string): Promise<Spec> {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source);
    if (!response.ok) throw new Error(`Could not fetch ${source}: ${response.status}`);
    return (await response.json()) as Spec;
  }
  return JSON.parse(await readFile(source, "utf8")) as Spec;
}

const upperFirst = (text: string) => text.charAt(0).toUpperCase() + text.slice(1);
const lowerFirst = (text: string) => text.charAt(0).toLowerCase() + text.slice(1);

/** The generator's class for a tag: `TikTok` → `TikTokApi`. */
const apiClass = (tag: string) => `${tag.replace(/[^A-Za-z0-9]/g, "")}Api`;

/** The client's property for a tag: `TikTok` → `tiktok`. */
const property = (tag: string) => tag.toLowerCase().replace(/[^a-z0-9]/g, "");

/** `tiktokPostCommentReplies` under `TikTok` → `postCommentReplies`. */
function methodName(operationId: string, tag: string): string {
  const prefix = property(tag);
  return operationId.toLowerCase().startsWith(prefix) && operationId.length > prefix.length
    ? lowerFirst(operationId.slice(prefix.length))
    : operationId;
}

function docComment(operation: Operation, path: string): string {
  const text = [operation.summary, operation.description]
    .filter(Boolean)
    .join(" ")
    .replace(/\s+/g, " ")
    .replace(/\*\//g, "*\\/")
    .trim();
  return `  /**\n   * ${text}\n   *\n   * \`GET ${path}\`\n   */`;
}

function render(spec: Spec): string {
  const groups = new Map<string, string[]>();
  const requestTypes: string[] = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    const operation = item.get;
    const tag = operation?.tags?.[0];
    if (!operation?.operationId || !tag) continue;
    const id = operation.operationId;
    const query = (operation.parameters ?? []).filter((p) => p.in === "query");
    const name = methodName(id, tag);
    let method: string;
    if (query.length === 0) {
      method = `${docComment(operation, path)}\n  ${name}(init?: Init) {\n    return call(() => this.api.${id}(init));\n  }`;
    } else {
      const type = `${upperFirst(id)}Request`;
      requestTypes.push(type);
      const optional = query.every((p) => !p.required);
      const params = optional ? `params: ${type} = {}` : `params: ${type}`;
      method = `${docComment(operation, path)}\n  ${name}(${params}, init?: Init) {\n    return call(() => this.api.${id}(params, init));\n  }`;
    }
    groups.set(tag, [...(groups.get(tag) ?? []), method]);
  }

  const tags = [...groups.keys()].sort((a, b) => (a === "Account" ? 1 : b === "Account" ? -1 : a.localeCompare(b)));
  const classes = tags.map(
    (tag) =>
      `/** ${tag === "Account" ? "Your workspace" : `${tag}'s endpoints`}, as \`client.${property(tag)}\`. */\nexport class ${tag.replace(/[^A-Za-z0-9]/g, "")}Endpoints {\n  constructor(private readonly api: ${apiClass(tag)}) {}\n\n${groups.get(tag)!.join("\n\n")}\n}`,
  );
  const fields = tags
    .map((tag) => `  /** ${tag === "Account" ? "Your workspace: its credits." : `${tag}.`} */\n  readonly ${property(tag)}: ${tag.replace(/[^A-Za-z0-9]/g, "")}Endpoints;`)
    .join("\n");
  const assignments = tags
    .map((tag) => `    this.${property(tag)} = new ${tag.replace(/[^A-Za-z0-9]/g, "")}Endpoints(new ${apiClass(tag)}(configuration));`)
    .join("\n");

  return `// Generated by scripts/generate-client.ts from the OpenAPI spec. Do not edit by hand.
import { ${tags.map(apiClass).join(", ")} } from "./apis/index.js";
import type { ${requestTypes.sort().join(", ")} } from "./apis/index.js";
import { call } from "./errors.js";
import { Configuration } from "./runtime.js";
import type { InitOverrideFunction } from "./runtime.js";

/** Per-call overrides of the underlying \`fetch\` (an \`AbortSignal\`, headers…). */
export type Init = RequestInit | InitOverrideFunction;

export interface SocialAPIOptions {
  /** Your API key (\`sapi_…\`). Defaults to the \`SOCIALAPI_API_KEY\` environment variable. */
  apiKey?: string;
  /** Defaults to \`https://api.socialapi.sh\`. */
  baseUrl?: string;
  /** A \`fetch\` to send requests with, instead of the global one. */
  fetch?: typeof fetch;
  /** Headers sent with every request. */
  headers?: Record<string, string>;
}

${classes.join("\n\n")}

/**
 * The SocialAPI client: one property per network, one method per endpoint.
 *
 * \`\`\`ts
 * const client = new SocialAPI({ apiKey: process.env.SOCIALAPI_API_KEY });
 * const { data } = await client.tiktok.profile({ handle: "nike" });
 * \`\`\`
 *
 * A refusal (\`404\`, \`403\`, \`402\`, \`429\`…) throws a \`SocialAPIError\` with its \`status\`
 * and \`code\`. Refusals cost no credits.
 */
export class SocialAPI {
${fields}

  constructor(options: SocialAPIOptions = {}) {
    const env = (globalThis as { process?: { env?: Record<string, string | undefined> } }).process?.env;
    const apiKey = options.apiKey ?? env?.SOCIALAPI_API_KEY;
    if (!apiKey) {
      throw new Error("Pass your API key as \`new SocialAPI({ apiKey })\`, or set SOCIALAPI_API_KEY.");
    }
    const configuration = new Configuration({
      basePath: (options.baseUrl ?? "https://api.socialapi.sh").replace(/\\/+$/, ""),
      accessToken: apiKey,
      fetchApi: options.fetch,
      headers: options.headers,
    });
${assignments}
  }
}
`;
}

let source = process.env.SPEC ?? DEFAULT_SPEC;
for (let i = 2; i < process.argv.length; i += 1) {
  if (process.argv[i] === "--spec") source = process.argv[(i += 1)]!;
  else throw new Error(`Unknown argument: ${process.argv[i]}`);
}
await writeFile("src/client.ts", render(await loadSpec(source)));
console.log("Wrote src/client.ts.");
